// Расшифровка кода из строки "J18.9 Пневмония" или "J18"
export function parseIcd(input: string): { code: string; name: string } {
  const raw = (input || "").trim();
  if (!raw) return { code: "", name: "" };
  const m = raw.match(/^([A-Za-zА-Яа-я]{0,1}\d{1,2}(?:\.\d{1,2})?)[\s.\-–—]*(.*)$/u);
  if (m) {
    const code = m[1].toUpperCase();
    let name = m[2].trim();
    if (!name) {
      const found = ICD10.find(([c]) => c.toUpperCase() === code);
      if (found) name = found[1];
    }
    return { code, name };
  }
  return { code: "", name: raw };
}
